import math

import pytest

from pyreinfolib import tiles
from pyreinfolib.tiles import MAX_LATITUDE, Bounds, Tile, bounds, containing, count_covering, covering

# The box and the point the README's examples use.
README_BOX = {"west": 139.665, "south": 35.640, "east": 139.724, "north": 35.679}
README_POINT = {"lon": 139.7016, "lat": 35.6580}

# Spread across the country, including the ends of it, so the round trip is not only ever
# exercised near Tokyo.
JAPANESE_POINTS = [
    ("那覇", 127.6809, 26.2124),
    ("福岡", 130.4017, 33.5904),
    ("大阪", 135.5023, 34.6937),
    ("渋谷", 139.7016, 35.6580),
    ("仙台", 140.8694, 38.2682),
    ("札幌", 141.3545, 43.0618),
    ("稚内", 141.6739, 45.4156),
    ("南鳥島", 153.9807, 24.2867),
]

ZOOM_LEVELS = list(range(0, 21))


class TestContaining:
    @pytest.mark.parametrize(
        ("lon", "lat", "expected"),
        [
            (-90.0, 45.0, Tile(z=1, x=0, y=0)),
            (90.0, 45.0, Tile(z=1, x=1, y=0)),
            (-90.0, -45.0, Tile(z=1, x=0, y=1)),
            (90.0, -45.0, Tile(z=1, x=1, y=1)),
        ],
        ids=["north-west", "north-east", "south-west", "south-east"],
    )
    def test_zoom_one_splits_the_world_into_quadrants_numbered_from_the_north_west(self, lon, lat, expected):
        """Expectations that follow from the XYZ scheme itself rather than from this module.

        The round trip below holds for any self-consistent grid, including TMS, which counts
        `y` from the south. These do not.
        """
        assert containing(lon=lon, lat=lat, z=1) == expected

    def test_a_point_always_falls_inside_the_bounds_of_its_own_tile(self):
        """The round trip, over every zoom level the API offers and then some.

        Checked as a property rather than against fixed expectations, because a table of
        expected tile numbers would be generated by the same arithmetic it is meant to test.
        """
        for name, lon, lat in JAPANESE_POINTS:
            for z in ZOOM_LEVELS:
                tile = containing(lon=lon, lat=lat, z=z)
                extent = bounds(tile)

                assert extent.west <= lon <= extent.east, f"{name} lon at z={z}: {extent}"
                assert extent.south <= lat <= extent.north, f"{name} lat at z={z}: {extent}"

    def test_y_increases_southward(self):
        """XYZ, not TMS. Under TMS every tile in this library would be in the wrong hemisphere."""
        north = containing(lon=139.7, lat=43.06, z=13)
        south = containing(lon=139.7, lat=26.21, z=13)

        assert north.y < south.y

    def test_x_increases_eastward(self):
        west = containing(lon=127.68, lat=35.0, z=13)
        east = containing(lon=141.35, lat=35.0, z=13)

        assert west.x < east.x

    @pytest.mark.parametrize("z", ZOOM_LEVELS)
    def test_the_world_edges_do_not_fall_off_the_grid(self, z):
        """The south-east corner computes to index `n`, one past the last tile, before clamping."""
        last = 2**z - 1

        assert containing(lon=180.0, lat=-MAX_LATITUDE, z=z) == Tile(z, last, last)
        assert containing(lon=-180.0, lat=MAX_LATITUDE, z=z) == Tile(z, 0, 0)

    @pytest.mark.parametrize(
        ("lon", "lat"),
        [(139.7, 35.66), (127.68, 26.21), (-180.0, 0.0), (180.0, 0.0)],
    )
    def test_it_returns_a_tile_within_the_grid(self, lon, lat):
        z = 15
        tile = containing(lon=lon, lat=lat, z=z)

        assert 0 <= tile.x < 2**z
        assert 0 <= tile.y < 2**z


class TestContainingRejectsBadInput:
    def test_the_latitude_limit_is_where_the_projected_world_is_square(self):
        """国土地理院 gives the cut-off as 約85.0511 度, and rounding to that would move the edge of
        the grid. The value in full is the latitude whose Mercator y is half the world's width.
        """
        assert MAX_LATITUDE == pytest.approx(math.degrees(math.atan(math.sinh(math.pi))))

    @pytest.mark.parametrize("lat", [90.0, 86.0, -86.0, -90.0], ids=str)
    def test_latitudes_web_mercator_cannot_place(self, lat):
        with pytest.raises(ValueError, match="lat"):
            containing(lon=139.7, lat=lat, z=15)

    @pytest.mark.parametrize("lon", [180.1, 360.0, -180.1], ids=str)
    def test_longitudes_off_the_world(self, lon):
        with pytest.raises(ValueError, match="lon"):
            containing(lon=lon, lat=35.66, z=15)

    @pytest.mark.parametrize("name,lon,lat", JAPANESE_POINTS, ids=lambda v: v if isinstance(v, str) else "")
    def test_swapping_latitude_and_longitude_is_caught(self, name, lon, lat):
        """The reason the arguments are keyword only.

        Japan spans 122E to 154E, so a longitude handed over as a latitude is always past the
        Web Mercator limit. It fails loudly instead of quietly describing somewhere else.
        """
        with pytest.raises(ValueError, match="lat"):
            containing(lon=lat, lat=lon, z=15)

    @pytest.mark.parametrize("z", [-1, -15])
    def test_negative_zoom(self, z):
        with pytest.raises(ValueError, match="z"):
            containing(lon=139.7, lat=35.66, z=z)


class TestBounds:
    def test_zoom_zero_is_the_whole_projected_world(self):
        extent = bounds(Tile(z=0, x=0, y=0))

        assert extent.west == pytest.approx(-180.0)
        assert extent.east == pytest.approx(180.0)
        assert extent.north == pytest.approx(MAX_LATITUDE)
        assert extent.south == pytest.approx(-MAX_LATITUDE)

    def test_adjacent_tiles_share_an_edge(self):
        """Gaps or overlaps here would make `covering` miss or duplicate data."""
        left = bounds(Tile(z=15, x=29099, y=12905))
        right = bounds(Tile(z=15, x=29100, y=12905))
        below = bounds(Tile(z=15, x=29099, y=12906))

        assert left.east == pytest.approx(right.west)
        assert left.south == pytest.approx(below.north)

    def test_it_returns_a_named_tuple_in_geojson_bbox_order(self):
        extent = bounds(Tile(z=13, x=7312, y=3008))

        assert isinstance(extent, Bounds)
        assert tuple(extent) == (extent.west, extent.south, extent.east, extent.north)
        assert extent.west < extent.east
        assert extent.south < extent.north


class TestCovering:
    def test_it_does_not_build_a_tile_before_it_is_asked_for(self, monkeypatch):
        """A prefecture at zoom 15 runs to thousands of tiles, so building a list up front
        would commit the caller to the whole thing before the first request.

        Counted rather than timed. The whole world at zoom 10 is about a million tiles, so an
        eager implementation fails here at once instead of making the test slow.
        """
        built = 0

        class CountingTile(Tile):
            def __new__(cls, *args: int, **kwargs: int):
                nonlocal built
                built += 1
                return super().__new__(cls, *args, **kwargs)

        monkeypatch.setattr(tiles, "Tile", CountingTile)

        world = covering(west=-180.0, south=-MAX_LATITUDE, east=180.0, north=MAX_LATITUDE, z=10)
        first = next(world)

        assert first == Tile(z=10, x=0, y=0)
        # The two corner tiles the extent is computed from, and the one yielded.
        assert built == 3

    def test_a_box_inside_one_tile_yields_that_tile_only(self):
        tile = Tile(z=13, x=7312, y=3008)
        extent = bounds(tile)
        inset_lon = (extent.east - extent.west) / 4
        inset_lat = (extent.north - extent.south) / 4

        result = list(
            covering(
                west=extent.west + inset_lon,
                south=extent.south + inset_lat,
                east=extent.east - inset_lon,
                north=extent.north - inset_lat,
                z=tile.z,
            )
        )

        assert result == [tile]

    def test_it_yields_every_tile_between_the_corner_tiles_once_row_by_row(self):
        """Compared whole, so a missing interior tile, a duplicate and the order all show here."""
        z = 15
        top_left = containing(lon=README_BOX["west"], lat=README_BOX["north"], z=z)
        bottom_right = containing(lon=README_BOX["east"], lat=README_BOX["south"], z=z)

        expected = [
            Tile(z, x, y) for y in range(top_left.y, bottom_right.y + 1) for x in range(top_left.x, bottom_right.x + 1)
        ]

        assert list(covering(**README_BOX, z=z)) == expected

    def test_every_tile_it_yields_overlaps_the_box(self):
        west, south, east, north = 139.665, 35.640, 139.724, 35.679

        for tile in covering(west=west, south=south, east=east, north=north, z=14):
            extent = bounds(tile)

            assert extent.west < east and extent.east > west, f"{tile} is outside in longitude"
            assert extent.south < north and extent.north > south, f"{tile} is outside in latitude"

    @pytest.mark.parametrize("z", [11, 12, 13, 14, 15])
    def test_count_covering_agrees_with_what_covering_yields(self, z):
        box = {"west": 139.562, "south": 35.520, "east": 139.920, "north": 35.818}

        assert count_covering(**box, z=z) == len(list(covering(**box, z=z)))

    @pytest.mark.parametrize("call", [covering, count_covering], ids=["covering", "count_covering"])
    def test_an_inverted_box_is_rejected(self, call):
        """Silently swapping the edges would hide a caller's mistake behind plausible data.

        Not wrapped in `list`, so this also pins where `covering` raises. Consuming the result
        first would let the check sit in a generator body and still pass.
        """
        with pytest.raises(ValueError, match="west"):
            call(west=139.9, south=35.5, east=139.5, north=35.9, z=13)

        with pytest.raises(ValueError, match="south"):
            call(west=139.5, south=35.9, east=139.9, north=35.5, z=13)

    @pytest.mark.parametrize(
        ("box", "expected"),
        [
            ({"west": 139.5, "south": 35.5, "east": 139.9, "north": 86.0}, "lat"),
            ({"west": 139.5, "south": -86.0, "east": 139.9, "north": 35.9}, "lat"),
            ({"west": -180.1, "south": 35.5, "east": 139.9, "north": 35.9}, "lon"),
            ({"west": 139.5, "south": 35.5, "east": 180.1, "north": 35.9}, "lon"),
        ],
        ids=["north past the limit", "south past the limit", "west off the world", "east off the world"],
    )
    def test_an_edge_outside_the_projected_world_is_rejected_by_the_call(self, box, expected):
        """These reach `covering` through `containing` rather than through `_corner_tiles`'s own
        checks, so they need pinning separately from the inverted box.
        """
        with pytest.raises(ValueError, match=expected):
            covering(**box, z=13)

        with pytest.raises(ValueError, match=expected):
            count_covering(**box, z=13)

    def test_a_negative_zoom_is_rejected_by_the_call(self):
        with pytest.raises(ValueError, match="z"):
            covering(west=139.5, south=35.5, east=139.9, north=35.9, z=-1)


class TestReadmeExamples:
    """The README prints these values. If one changes, the README is wrong."""

    def test_containing(self):
        assert containing(**README_POINT, z=15) == Tile(z=15, x=29099, y=12905)

    def test_count_covering(self):
        assert count_covering(**README_BOX, z=15) == 30

    def test_bounds(self):
        extent = bounds(Tile(z=15, x=29099, y=12905))

        assert extent == pytest.approx(
            Bounds(west=139.691162109375, south=35.65729624809628, east=139.7021484375, north=35.66622234103478)
        )
